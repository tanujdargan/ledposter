#!/usr/bin/env python3
"""Generates engine/src/clockfont.h: the clock overlay's two antialiased fonts as alpha bitmaps.

  python3 tools/clockfont.py Inter-VariableFont_slnt,wght.ttf > engine/src/clockfont.h

Inter (https://rsms.me/inter, SIL Open Font License 1.1), rasterized here once with Pillow so
the engine needs no font library and does no rasterizing on the Pi: the time in Inter Light,
the date in Inter Medium, small caps-height text with a little tracking. Needs Pillow; the
variable font, so both weights come from one file (a static TTF works too, at its own weight).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

# name, size px, weight, tracking px, characters
FONTS = [
    ("kClockTime", 32, 300, 1, "0123456789:"),
    ("kClockDate", 9, 500, 1, "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 "),
]


def load(path, size, weight):
    f = ImageFont.truetype(path, size)
    try:
        f.set_variation_by_axes([weight] + [0] * (len(f.get_variation_axes()) - 1))
    except OSError:  # not a variable font
        pass
    return f


def glyphs(font, chars, tracking):
    out = []
    for ch in chars:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")  # origin: pen position on the baseline
        adv = round(font.getlength(ch)) + tracking
        if x1 <= x0 or y1 <= y0:  # space
            out.append([ord(ch), 0, 0, 0, 0, adv, b""])
            continue
        im = Image.new("L", (x1 - x0, y1 - y0))
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        ix0, iy0, ix1, iy1 = im.getbbox()  # the ink only: getbbox includes the side bearings
        im = im.crop((ix0, iy0, ix1, iy1))
        out.append([ord(ch), x0 + ix0, y0 + iy0, im.width, im.height, adv, im.tobytes()])
    by = {g[0]: g for g in out}
    if ord(":") in by and ord("0") in by:  # the time's colon sits mid-height of the digits
        c, z = by[ord(":")], by[ord("0")]
        c[2] = z[2] + (z[4] - c[4]) // 2
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    w = sys.stdout.write
    w("// Generated by tools/clockfont.py: do not edit. The clock overlay's fonts, rasterized from\n"
      "// Inter (https://rsms.me/inter, SIL Open Font License 1.1, Copyright the Inter Project Authors).\n"
      "// Per glyph: x, y from the pen on the baseline to the bitmap's top-left (y < 0 is above),\n"
      "// w x h alpha bytes at off in the font's alpha array, adv includes the tracking.\n"
      "#pragma once\n#include <cstdint>\n\n"
      "struct AaGlyph {\n  uint32_t cp;\n  int x, y, w, h, adv;\n  uint32_t off;\n};\n"
      "struct AaFont {\n  const AaGlyph *glyphs;\n  int n;\n  const uint8_t *alpha;\n"
      "  const AaGlyph *get(uint32_t cp) const {\n"
      "    for (int i = 0; i < n; i++)\n      if (glyphs[i].cp == cp) return &glyphs[i];\n"
      "    return nullptr;\n  }\n};\n")
    for name, size, weight, tracking, chars in FONTS:
        gs = glyphs(load(sys.argv[1], size, weight), chars, tracking)
        alpha, table = bytearray(), []
        for cp, x, y, gw, gh, adv, a in gs:
            table.append(f"    {{{cp}, {x}, {y}, {gw}, {gh}, {adv}, {len(alpha)}}},  // {chr(cp)!r}")
            alpha += a
        w(f"\n// Inter {size}px, weight {weight}, tracking {tracking}px\n")
        w(f"inline const uint8_t {name}Alpha[] = {{\n")
        for i in range(0, len(alpha), 24):
            w("    " + ",".join(str(v) for v in alpha[i:i + 24]) + ",\n")
        w("};\n")
        w(f"inline const AaGlyph {name}Glyphs[] = {{\n" + "\n".join(table) + "\n};\n")
        w(f"inline const AaFont {name}{{{name}Glyphs, {len(gs)}, {name}Alpha}};\n")


if __name__ == "__main__":
    main()
